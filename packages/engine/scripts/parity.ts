/**
 * Writes docs/parity.md (headline golden numbers + every O_Outlook cell + per-sheet summary)
 * and docs/parity-cells.csv (every compared cell). Run: pnpm parity
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { Decimal } from "../src/decimal";
import { computeWeek } from "../src/week";
import { loadFixtureWeek, loadGolden, repoRoot } from "../src/fixtures";
import { fixed } from "../src/format";
import { buildChecks, compare, enToId, type Check } from "../test/golden-map";

const WEEK = "2026-08-24";
const r = computeWeek(loadFixtureWeek(WEEK));
const g = loadGolden(WEEK);
const checks = buildChecks(r, g);
const byCell = new Map(checks.map((c) => [c.cell, c]));

function show(v: string | null, kind: Check["kind"], excel = false): string {
  if (v === null || v === "") return "—";
  if (kind === "text") return excel ? enToId(v) : v;
  if (kind === "key" || kind === "date") return v;
  const d = new Decimal(v);
  if (kind === "ratio") return fixed(d, 6).replace(/,?0+$/, "") || "0";
  if (kind === "kg") return fixed(d, 2);
  if (kind === "count") return fixed(d, 0);
  return fixed(d, 2);
}

const status = (c: Check) => (compare(c).ok ? "✅ LULUS" : `❌ GAGAL (${compare(c).diff})`);

const headline: [string, string[]][] = [
  ["Week summary — kg actual to yesterday / projected week (23.588 / 64.025 kg)", ["O_Outlook!B8", "O_Outlook!H8"]],
  ["Projected product GP KGR (−47,6 jt); GP/kg (−743)", ["O_Outlook!J8", "O_Outlook!K8"]],
  ["RPA: fresh orders in horizon / stock fresh today (12.307 / 18.768 kg)", ["O_Outlook!B13", "O_Outlook!B14"]],
  ["RPA: net need 0, LB max 0", ["O_Outlook!B15", "O_Outlook!B16"]],
  ["RPA: planned LB in horizon (27.219 kg); karkas at risk of freezing (19.475 kg)", ["O_Outlook!B17", "O_Outlook!B18"]],
  ["RPA: breakeven at plan share / at 100% fresh (Rp 20.726 / Rp 24.337)", ["O_Outlook!B21", "O_Outlook!B22"]],
  ["RPA: margin at Rp 24.600 (−3.874)", ["O_Outlook!B12", "O_Outlook!B23"]],
  ["RPA recommendation (TUNDA / NEGOSIASI)", ["O_Outlook!B26"]],
  ["Trading: BLP Frozen (CEK HARGA, order 43.086 < avg cost 47.199)", ["O_Outlook!K32", "O_Outlook!F32", "O_Outlook!J32"]],
  ["Trading: BLD Frozen (JUAL STOK 4.848 kg)", ["O_Outlook!K30"]],
  ["Stock actions: KURANG 0; JUAL 23 keys / 17.834 kg; PERHATIAN 7 keys / 116.290 kg",
    ["O_Outlook!B44", "O_Outlook!B45", "O_Outlook!C45", "O_Outlook!B46", "O_Outlook!C46"]],
  ["Batches: actual shrink / karkas yield / fresh % (6,3% / 73,8% / 66,6%, 2 batches)",
    ["O_Outlook!B61", "O_Outlook!E61", "O_Outlook!F61", "O_Outlook!G61"]],
  ["P&L projection: revenue / GP / NI (1.656,8 / −67,5 / −107,6 jt)", ["O_PnL!E9", "O_PnL!E15", "O_PnL!E37"]],
  ["P&L last week NI / MTD actual NI (−111,0 / +165,2 jt)", ["O_PnL!B37", "O_PnL!G37"]],
  ["BS projected: total assets (8.531,3 jt); control 0 in all columns",
    ["O_BS!E20", "O_BS!B39", "O_BS!C39", "O_BS!D39", "O_BS!E39", "O_BS!F39"]],
  ["BS projected: cash / inventory / affiliate payables (818,2 / 3.992,4 / 5.600,0 jt)",
    ["O_BS!E7", "O_Outlook!C83", "O_BS!E26"]],
  ["CF projected: net / customer receipts / supplier payments (+439,1 / 1.872,9 / −1.325,0 jt)", ["O_CF!E18", "O_CF!E6", "O_CF!E8"]],
  ["CF: lowest daily cash balance (289,7 jt on 28 Aug)", ["O_CF!C35", "O_CF!C32"]],
  ["Controls (17 LULUS, 2 BELUM DIISI)", ["Z_Kontrol!F12", "Z_Kontrol!F13", "Z_Kontrol!F25"]],
];

const lines: string[] = [];
const now = "generated by `pnpm parity`";
lines.push("# Parity — engine vs reference Excel");
lines.push("");
lines.push(`Example week ${r.week.weekStart} – ${r.week.weekEnd}, update date ${r.week.today}. Source: \`reference/KGR_Weekly_Outlook.xlsx\` (cached values extracted by \`scripts/extract_fixtures.py\` into \`fixtures/week-${WEEK}/golden.json\`). Tolerance: Rp 1, 0,01 kg, ratios 1e-9; texts compared after converting Excel's en-US \`FIXED()\` numbers to the house format. File ${now}.`);
lines.push("");
const total = checks.length;
const okN = checks.filter((c) => compare(c).ok).length;
lines.push(`**Status: ${okN} / ${total} cells match** (${okN === total ? "all green" : `${total - okN} open`}).`);
lines.push("");
lines.push("## 1. PRD §10 golden numbers");
lines.push("");
lines.push("| Item | Source cell | Expected (Excel) | Actual (engine) | Status |");
lines.push("| --- | --- | ---: | ---: | --- |");
for (const [label, cells] of headline) {
  cells.forEach((cell, i) => {
    const c = byCell.get(cell);
    if (!c) throw new Error(`no check for ${cell}`);
    lines.push(`| ${i === 0 ? label : ""} | \`${cell}\` | ${show(c.expected, c.kind, true)} | ${show(c.actual, c.kind)} | ${status(c)} |`);
  });
}
lines.push("");
lines.push("## 2. O_Outlook — every cell of blocks 1–8");
lines.push("");
lines.push("| Cell | Item | Expected (Excel) | Actual (engine) | Status |");
lines.push("| --- | --- | ---: | ---: | --- |");
for (const c of checks.filter((x) => x.cell.startsWith("O_Outlook!"))) {
  lines.push(`| \`${c.cell}\` | ${c.label.replace(/\|/g, "\\|")} | ${show(c.expected, c.kind, true).replace(/\|/g, "\\|")} | ${show(c.actual, c.kind).replace(/\|/g, "\\|")} | ${status(c)} |`);
}
lines.push("");
lines.push("## 3. Per-sheet summary (all compared cells)");
lines.push("");
lines.push("| Sheet | Cells | Match | Max abs diff (numeric) | Status |");
lines.push("| --- | ---: | ---: | ---: | --- |");
const sheets = [...new Set(checks.map((c) => c.cell.split("!")[0]))];
for (const s of sheets) {
  const xs = checks.filter((c) => c.cell.startsWith(s + "!"));
  const ok = xs.filter((c) => compare(c).ok).length;
  let maxd = new Decimal(0);
  for (const c of xs) {
    if (["rp", "kg", "ratio", "count"].includes(c.kind) && c.expected && c.actual) {
      const d = new Decimal(c.actual).minus(new Decimal(c.expected)).abs();
      if (d.greaterThan(maxd)) maxd = d;
    }
  }
  lines.push(`| ${s} | ${xs.length} | ${ok} | ${maxd.toSignificantDigits(3).toString()} | ${ok === xs.length ? "✅" : "❌"} |`);
}
lines.push("");
lines.push("Every compared cell with expected and actual values: [`docs/parity-cells.csv`](parity-cells.csv).");
lines.push("");
lines.push("Statements (O_PnL, O_BS, O_CF) and Z_Kontrol are part of M4 and are already compared cell by cell above.");
lines.push("");

const root = repoRoot();
writeFileSync(join(root, "docs", "parity.md"), lines.join("\n"));
const csv = ["cell,label,kind,expected,actual,ok,diff"];
const q = (s: string | null) => (s === null ? "" : `"${s.replace(/"/g, '""')}"`);
for (const c of checks) {
  const k = compare(c);
  csv.push([c.cell, q(c.label), c.kind, q(c.expected), q(c.actual), k.ok ? "1" : "0", q(k.diff)].join(","));
}
writeFileSync(join(root, "docs", "parity-cells.csv"), csv.join("\n") + "\n");
console.log(`parity: ${okN}/${total} cells match → docs/parity.md, docs/parity-cells.csv`);
if (okN !== total) process.exit(1);
